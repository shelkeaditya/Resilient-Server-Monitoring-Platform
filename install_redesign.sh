#!/usr/bin/env bash
# Server Monitor - dashboard redesign installer.
# Usage:  bash install_redesign.sh [/path/to/project]      (default /mnt/data/projects/monitor)
#
# What it does: backs up the files it will replace, installs the new ones, runs the full
# verification suite, restarts the 'monitor' systemd service and checks /healthz.
# If a check fails it restores the backup automatically. nginx and systemd units are not touched.
set -euo pipefail

PROJECT="${1:-/mnt/data/projects/monitor}"
SERVICE="monitor"
cd "$PROJECT"
[ -f app/app.py ] && [ -d app/monitor ] && [ -x venv/bin/python ] || { echo "ERROR: $PROJECT does not look like the monitor project"; exit 1; }
if [ "$(wc -c < app/static/vendor/chart.umd.min.js 2>/dev/null || echo 0)" -lt 100000 ] || ! grep -q "Chart.js" app/static/vendor/chart.umd.min.js; then
  echo "ERROR: app/static/vendor/chart.umd.min.js is missing or is not the Chart.js library."
  echo "       Re-download it:  curl -L https://cdn.jsdelivr.net/npm/chart.js@4.4.7/dist/chart.umd.min.js -o app/static/vendor/chart.umd.min.js"
  exit 1
fi

# Port the service listens on: MONITOR_PORT=... overrides, otherwise read it from the systemd unit.
PORT="${MONITOR_PORT:-}"
if [ -z "$PORT" ]; then
  PORT="$(systemctl cat "$SERVICE" 2>/dev/null | grep -oE -- '--listen=[^ ]+' | head -1 | grep -oE '[0-9]+$' || true)"
fi
PORT="${PORT:-5000}"
BASE="http://127.0.0.1:$PORT"
echo "==> Using $SERVICE at $BASE"

STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP="$PROJECT/.backup-before-redesign-$STAMP"
mkdir -p "$BACKUP"
echo "==> Backing up current files to $BACKUP"
for p in app/app.py app/monitor app/templates app/static verification; do
  [ -e "$p" ] && cp -a --parents "$p" "$BACKUP"/
done
grep -qxF '.backup-*/' .gitignore 2>/dev/null || echo '.backup-*/' >> .gitignore

rollback() {
  echo "!! $1 - restoring the previous version"
  echo "---- last service log lines (for diagnosis) ----"
  sudo journalctl -u "$SERVICE" -n 20 --no-pager 2>/dev/null || true
  echo "-------------------------------------------------"
  cp -a "$BACKUP"/app "$BACKUP"/verification "$PROJECT"/ 2>/dev/null || true
  sudo systemctl restart "$SERVICE" || true
  echo "Restored from $BACKUP"
  exit 1
}

